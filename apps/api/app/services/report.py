def generate_pdf_report(topology: Topology) -> bytes:
    lines = _wrap_pdf_lines(_plain_report_lines(topology))
    pages = [lines[index:index + 48] for index in range(0, len(lines), 48)] or [[]]

    objects: list[bytes] = []
    page_object_ids: list[int] = []

    def add_object(content: bytes) -> int:
        objects.append(content)
        return len(objects)

    catalog_id = add_object(b"<< /Type /Catalog /Pages 2 0 R >>")
    pages_id = add_object(b"")
    font_id = add_object(b"<< /Type /Font /Subtype /Type1 /BaseFont /Courier >>")

    for page_lines in pages:
        stream = _pdf_text_stream(page_lines)
        stream_id = add_object(
            b"<< /Length " + str(len(stream)).encode("ascii") + b" >>\nstream\n"
            + stream
            + b"\nendstream"
        )
        page_id = add_object(
            b"<< /Type /Page /Parent "
            + str(pages_id).encode("ascii")
            + b" 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 "
            + str(font_id).encode("ascii")
            + b" 0 R >> >> /Contents "
            + str(stream_id).encode("ascii")
            + b" 0 R >>"
        )
        page_object_ids.append(page_id)

    kids = b" ".join(f"{page_id} 0 R".encode("ascii") for page_id in page_object_ids)
    objects[pages_id - 1] = (
        b"<< /Type /Pages /Kids ["
        + kids
        + b"] /Count "
        + str(len(page_object_ids)).encode("ascii")
        + b" >>"
    )

    return _serialize_pdf(objects, catalog_id)


def _csv(values: Iterable[str]) -> str:
    items = [value for value in values if value]
    return ", ".join(items) if items else "none"


def _node_inventory_table(nodes) -> str:
    if not nodes:
        return "_No nodes in this topology._"

    rows = [
        "| Label | Type | Role | Protocols | Loopback | Vendor | Platform |",
        "|---|---|---|---|---|---|---|",
    ]
    for node in nodes:
        rows.append(
            "| "
            + " | ".join(
                [
                    node.label,
                    node.baseType,
                    node.role or "-",
                    _csv(node.protocols),
                    node.loopback or "-",
                    node.vendor or "-",
                    node.platform or "-",
                ]
            )
            + " |"
        )
    return "\n".join(rows)


def _interface_table(nodes) -> str:
    interfaces = [interface for node in nodes for interface in node.interfaces]
    if not interfaces:
        return "_No interfaces derived from links._"

    rows = [
        "| Node | Port | IP | Subnet | Peer Node | Peer Port | Link |",
        "|---|---|---|---|---|---|---|",
    ]
    for interface in interfaces:
        rows.append(
            "| "
            + " | ".join(
                [
                    interface.nodeId,
                    interface.port,
                    interface.ip or "-",
                    interface.subnet or "-",
                    interface.peerNodeId,
                    interface.peerPort,
                    interface.linkId,
                ]
            )
            + " |"
        )
    return "\n".join(rows)


def _link_table(links) -> str:
    if not links:
        return "_No links in this topology._"

    rows = [
        "| Link ID | Source | Target | Type | Subnet | QoS | Fault State |",
        "|---|---|---|---|---|---|---|",
    ]
    for link in links:
        qos = "-"
        if link.qos:
            qos = ", ".join(f"{key}={value}" for key, value in link.qos.items() if value is not None)
            qos = qos or "-"
        fault_state = "-"
        if link.faultState:
            fault_state = ", ".join(
                f"{key}={value}" for key, value in link.faultState.items() if value is not None
            )
            fault_state = fault_state or "-"
        rows.append(
            "| "
            + " | ".join(
                [
                    link.id,
                    f"{link.sourceNodeId}:{link.sourcePort}",
                    f"{link.targetNodeId}:{link.targetPort}",
                    link.linkType,
                    link.subnet or "-",
                    qos,
                    fault_state,
                ]
            )
            + " |"
        )
    return "\n".join(rows)


