def _plain_node_inventory(nodes) -> list[str]:
    if not nodes:
        return ["  No nodes in this topology."]

    lines = ["  Label                 Type       Role       Protocols       Loopback"]
    lines.append("  " + "-" * 74)
    for node in nodes:
        lines.append(
            f"  {node.label[:20]:20}  {node.baseType[:9]:9}  {(node.role or '-')[:9]:9}  "
            f"{_csv(node.protocols)[:14]:14}  {node.loopback or '-'}"
        )
    return lines


def _plain_interfaces(nodes) -> list[str]:
    interfaces = [interface for node in nodes for interface in node.interfaces]
    if not interfaces:
        return ["  No interfaces derived from links."]

    lines = ["  Node                  Port    IP               Subnet           Peer"]
    lines.append("  " + "-" * 82)
    for interface in interfaces:
        peer = f"{interface.peerNodeId}:{interface.peerPort}"
        lines.append(
            f"  {interface.nodeId[:20]:20}  {interface.port[:6]:6}  "
            f"{(interface.ip or '-')[:15]:15}  {(interface.subnet or '-')[:15]:15}  {peer}"
        )
    return lines


def _plain_links(links) -> list[str]:
    if not links:
        return ["  No links in this topology."]

    lines = ["  Link ID               Source                 Target                 Subnet"]
    lines.append("  " + "-" * 86)
    for link in links:
        lines.append(
            f"  {link.id[:20]:20}  {f'{link.sourceNodeId}:{link.sourcePort}'[:20]:20}  "
            f"{f'{link.targetNodeId}:{link.targetPort}'[:20]:20}  {link.subnet or '-'}"
        )
    return lines


def _plain_routing(topology: TopologyBase) -> list[str]:
    lines = []
    for node in topology.nodes:
        logical_config = node.logicalConfig or {}
        routing_config = logical_config.get("routingConfig") or {}
        protocols = node.protocols or []
        if protocols or routing_config:
            lines.append(
                f"  {node.label}: protocols={_csv(protocols)}, "
                f"process={routing_config.get('processId', '-')}, "
                f"area={routing_config.get('area', '-')}, "
                f"router-id={routing_config.get('routerId', '-')}"
            )
    return lines or ["  No routing configuration found."]


def _wrap_pdf_lines(lines: list[str]) -> list[str]:
    wrapped: list[str] = []
    for line in lines:
        safe_line = line if line else " "
        while len(safe_line) > 92:
            wrapped.append(safe_line[:92])
            safe_line = safe_line[92:]
        wrapped.append(safe_line)
    return wrapped


def _pdf_text_stream(lines: list[str]) -> bytes:
    commands = ["BT", "/F1 9 Tf", "50 750 Td", "12 TL"]
    for line in lines:
        commands.append(f"({_escape_pdf_text(line)}) Tj")
        commands.append("T*")
    commands.append("ET")
    return "\n".join(commands).encode("latin-1", errors="replace")


def _escape_pdf_text(text: str) -> str:
    encoded = text.encode("latin-1", errors="replace").decode("latin-1")
    return encoded.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")


def _serialize_pdf(objects: list[bytes], catalog_id: int) -> bytes:
    output = bytearray(b"%PDF-1.4\n")
    offsets = [0]
    for index, content in enumerate(objects, start=1):
        offsets.append(len(output))
        output.extend(f"{index} 0 obj\n".encode("ascii"))
        output.extend(content)
        output.extend(b"\nendobj\n")

    xref_offset = len(output)
    output.extend(f"xref\n0 {len(objects) + 1}\n".encode("ascii"))
    output.extend(b"0000000000 65535 f \n")
    for offset in offsets[1:]:
        output.extend(f"{offset:010d} 00000 n \n".encode("ascii"))
    output.extend(
        b"trailer\n"
        + b"<< /Size "
        + str(len(objects) + 1).encode("ascii")
        + b" /Root "
        + str(catalog_id).encode("ascii")
        + b" 0 R >>\nstartxref\n"
        + str(xref_offset).encode("ascii")
        + b"\n%%EOF\n"
    )
    return bytes(output)
